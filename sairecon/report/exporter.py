"""
SaiRecon report exporters.
Both functions return the output path on success, or None on failure — they
never raise, so a broken export never crashes the CLI.
"""
from __future__ import annotations

import json
import os
from typing import Optional

from sairecon.config import VERSION


def export_json(scan_result: dict, output_path: str) -> Optional[str]:
    """Write scan_result to a JSON file. Returns path on success, None on failure."""
    try:
        out = dict(scan_result)
        out.setdefault("sairecon_version", VERSION)
        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        with open(output_path, "w", encoding="utf-8") as f:
            json.dump(out, f, indent=2, default=str)
        return output_path
    except (OSError, PermissionError, IOError) as exc:
        print(f"[export_json] ERROR writing {output_path}: {exc}", flush=True)
        return None
    except (TypeError, ValueError) as exc:
        print(f"[export_json] ERROR serialising result: {exc}", flush=True)
        return None


def export_markdown(scan_result: dict, output_path: str) -> Optional[str]:
    """Generate a Markdown report. Returns path on success, None on failure."""
    try:
        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        findings = scan_result.get("findings", [])
        sev_order = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 4, None: 5}
        findings = sorted(findings, key=lambda f: sev_order.get(f.get("severity"), 5))

        sev_counts = {"critical": 0, "high": 0, "medium": 0, "low": 0, "info": 0}
        for f in findings:
            s = f.get("severity")
            if s in sev_counts:
                sev_counts[s] += 1

        modules_status = scan_result.get("modules_status", {})
        ok_count   = sum(1 for s in modules_status.values() if s == "ok")
        fail_count = sum(1 for s in modules_status.values() if s == "failed")
        skip_count = sum(1 for s in modules_status.values() if s == "skipped")

        lines = []
        lines.append(f"# SaiRecon Report — {scan_result.get('target_raw', '')}")
        lines.append("")
        lines.append("| Field | Value |")
        lines.append("|---|---|")
        lines.append(f"| Target | `{scan_result.get('target_raw')}` |")
        lines.append(f"| Apex domain | `{scan_result.get('apex_domain')}` |")
        lines.append(f"| Scope | {'Wildcard' if scan_result.get('is_wildcard') else 'Single host'} |")
        lines.append(f"| Started | {scan_result.get('started_at')} |")
        lines.append(f"| Duration | {scan_result.get('duration_sec')}s |")
        lines.append(f"| SaiRecon version | {scan_result.get('sairecon_version', VERSION)} |")
        lines.append("")
        lines.append("## Summary")
        lines.append("")
        lines.append("| Severity | Count |")
        lines.append("|---|---|")
        for s, c in sev_counts.items():
            lines.append(f"| {s.capitalize()} | {c} |")
        lines.append(f"| **Total findings** | **{len(findings)}** |")
        lines.append(f"| Resolved hosts | {len(scan_result.get('resolved_hosts', []))} |")
        lines.append(f"| Live hosts | {len(scan_result.get('live_hosts', []))} |")
        lines.append(f"| Modules OK | {ok_count} |")
        lines.append(f"| Modules Failed | {fail_count} |")
        lines.append(f"| Modules Skipped | {skip_count} |")
        lines.append("")
        lines.append("## Findings")
        lines.append("")

        for f in findings:
            sev = (f.get("severity") or "info").upper()
            lines.append(f"### [{sev}] {f.get('title', '')}")
            lines.append("")
            lines.append(f"**Module:** `{f.get('source_module')}`  ")
            lines.append(f"**Command:** `{f.get('command')}`")
            lines.append("")
            result = f.get("result", {})
            lines.append("```json")
            try:
                lines.append(json.dumps(result, indent=2, default=str)[:3000])
            except (TypeError, ValueError):
                lines.append(str(result)[:3000])
            lines.append("```")
            lines.append("")

        lines.append("---")
        lines.append(f"*Generated by SaiRecon v{VERSION} — recon-only, no attack code.*")

        with open(output_path, "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines))
        return output_path

    except (OSError, PermissionError, IOError) as exc:
        print(f"[export_markdown] ERROR writing {output_path}: {exc}", flush=True)
        return None
    except Exception as exc:
        print(f"[export_markdown] Unexpected error: {type(exc).__name__}: {exc}", flush=True)
        return None
